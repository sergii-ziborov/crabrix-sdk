import { build } from "esbuild";
import { mkdir, readFile, readdir, writeFile, chmod, copyFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
const root = path.dirname(fileURLToPath(import.meta.url));
const packageInfo = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
const versionSource = await readFile(path.join(root, "src/version.ts"), "utf8");
if (!versionSource.includes(`SDK_VERSION = "${packageInfo.version}"`)) throw new Error("CLI and package versions must match.");
const cargoVersion = (await readFile(path.join(root, "crates/crabrix/Cargo.toml"), "utf8")).match(/^version\s*=\s*"([^"]+)"$/m)?.[1];
if (cargoVersion !== packageInfo.version) throw new Error("Cargo and npm release versions must match.");
// package.json is the one version source. Everything a client installs from is generated.
const MCP_NAME = "io.github.sergii-ziborov/crabrix", TESTED_PROTOCOLS = ["2025-11-25"];
if (packageInfo.mcpName !== MCP_NAME) throw new Error("package.json mcpName must match the MCP Registry name.");
const writeJSON = (file, value) => writeFile(path.join(root, file), JSON.stringify(value, null, 2) + "\n");
const npxArgs = ["-y", `crabrix@${packageInfo.version}`];
await writeJSON(".mcp.json", { mcpServers: { crabrix: { command: "npx", args: npxArgs } } });
const plugin = JSON.parse(await readFile(path.join(root, ".claude-plugin/plugin.json"), "utf8"));
await writeJSON(".claude-plugin/plugin.json", { ...plugin, version: packageInfo.version });
await writeJSON("server.json", {
  $schema: "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
  name: MCP_NAME, title: "Crabrix", description: "Temporary encrypted Rust Playgrounds shared by agents and people, with permissioned local Run/Debug.",
  websiteUrl: "https://crabrix.com/ai/", repository: { url: "https://github.com/sergii-ziborov/crabrix-sdk", source: "github" }, version: packageInfo.version,
  packages: [{ registryType: "npm", registryBaseUrl: "https://registry.npmjs.org", identifier: "crabrix", version: packageInfo.version, runtimeHint: "npx", transport: { type: "stdio" } }],
});
await writeFile(path.join(root, "go/crabrix/version.go"), `// Code generated by build.mjs; DO NOT EDIT.\npackage crabrix\n\nconst Version = "${packageInfo.version}"\n`);
const result = await build({ absWorkingDir: root, entryPoints: ["src/cli.ts"], outdir: "dist", outExtension: {".js":".mjs"}, bundle: true, platform: "node", target: "node22", format: "esm", metafile: true,
  define: { __CRABRIX_RELEASE_VERSION__: JSON.stringify(packageInfo.version) },
  // A few SDK dependencies still use CJS builtins. createRequire resolves only
  // bundled dependencies/builtins, never project-controlled module paths.
  banner: { js: 'import { createRequire as __crabrixCreateRequire } from "node:module"; const require = __crabrixCreateRequire(import.meta.url);' } });
await chmod(path.join(root, "dist/cli.mjs"), 0o755);
const library = await build({absWorkingDir:root,entryPoints:["src/runtime-entry.ts"],outfile:"dist/implementation.cjs",bundle:true,platform:"node",target:"node22",format:"cjs",metafile:true});
await writeFile(path.join(root,"dist/index.cjs"),'const core = require("./implementation.cjs"); module.exports = { Crabrix: core.Crabrix, CrabrixError: core.CrabrixError, PLAYGROUND_LIMITS: core.PLAYGROUND_LIMITS };\n');
await writeFile(path.join(root,"dist/index.mjs"),'import core from "./implementation.cjs"; export const Crabrix = core.Crabrix; export const CrabrixError = core.CrabrixError; export const PLAYGROUND_LIMITS = core.PLAYGROUND_LIMITS;\n');
await writeFile(path.join(root,"dist/server.mjs"),'import core from "./implementation.cjs"; export const makeServer = core.makeServer;\n');
execFileSync(process.execPath,["node_modules/typescript/bin/tsc","--noEmit","false","--declaration","--emitDeclarationOnly","--outDir","dist","--rootDir","src"],{cwd:root,stdio:"inherit"});
const packages = new Map();
const bundledInputs = new Set([...Object.keys(result.metafile.inputs), ...Object.keys(library.metafile.inputs)]);
for (const input of bundledInputs) {
  if (!input.includes("node_modules")) continue;
  let directory = path.dirname(path.resolve(root, input));
  while (directory !== path.dirname(directory)) {
    try {
      const info = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
      if (info.name && info.version) { packages.set(info.name + "@" + info.version, { directory, info }); break; }
    } catch {}
    directory = path.dirname(directory);
  }
}
const notices = ["Crabrix SDK — third-party components\nOriginal component licenses apply independently of the Crabrix bridge license.\n"];
for (const [name, { directory, info }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  let license;
  for (const file of ["LICENSE", "LICENSE.txt", "LICENSE.md", "license", "license.md"]) { try { license = await readFile(path.join(directory, file), "utf8"); break; } catch {} }
  if (!license) throw new Error("Missing license text: " + name);
  notices.push(`\n${"=".repeat(72)}\n${name} · ${info.license ?? "see original text"}\n${license}`);
  for (const file of ["NOTICE", "NOTICE.txt", "NOTICE.md"]) { try { notices.push(await readFile(path.join(directory, file), "utf8")); } catch {} }
}
await mkdir(path.join(root, "dist"), { recursive: true });
await writeFile(path.join(root, "ThirdPartyNotices.txt"), notices.join("\n"));
await writeFile(path.join(root, "dist/components.json"), JSON.stringify([...packages].map(([name, { info }]) => ({ name, license: info.license })), null, 2) + "\n");
const sources = {};
const repository = root;
for (const input of new Set([...bundledInputs].filter(file => !file.includes("node_modules")).concat(["src/types.ts", "src/core/provenance.json", "build.mjs", "tsconfig.json", "package.json", "LICENSE", "README.md"]))) {
  const file = path.resolve(root, input), relative = path.relative(repository, file);
  if (relative.startsWith("..") || path.isAbsolute(relative)) throw new Error("Bundled source is outside the repository.");
  sources[relative.split(path.sep).join("/")] = createHash("sha256").update(await readFile(file)).digest("hex");
}
await writeFile(path.join(root, "dist/source-manifest.json"), JSON.stringify({ version: JSON.parse(await readFile(path.join(root, "package.json"), "utf8")).version, sourceSHA256: sources }, null, 2) + "\n");

// Public declarations are self-contained: consumers do not need Yjs or MCP SDK types.
const publicTypes = await readFile(path.join(root,"dist/types.d.ts"),"utf8");
const publicAPI = (await readFile(path.join(root,"dist/index.d.ts"),"utf8")).split("\n").filter(line=>!line.startsWith("import type ")&&!line.startsWith("export type *")&&!line.startsWith("export { PLAYGROUND_LIMITS")&&!line.startsWith("export { CrabrixError")).join("\n");
const declarations=publicTypes+"\nexport declare const PLAYGROUND_LIMITS: Readonly<{files:16;fileBytes:number;sourceBytes:number;maximumLifetimeSeconds:number;participants:4}>;\nexport declare class CrabrixError extends Error { readonly code: string; readonly retryable: boolean; readonly action: string; readonly details?: Record<string, unknown>; toJSON(): Record<string, unknown>; }\n"+publicAPI;
await writeFile(path.join(root,"dist/index.d.ts"),'export * from "./index.cjs";\n');
await writeFile(path.join(root,"dist/index.d.cts"),declarations);

// Release every language binding from these exact bridge bytes. A rebuilt npm
// executable must never silently leave Cargo/Go embedding an older protocol.
const bridge = await readFile(path.join(root, "dist/cli.mjs"));
for (const directory of ["crates/crabrix", "go/crabrix"]) {
  await writeFile(path.join(root, directory, "runtime/bridge.mjs"), bridge);
  await copyFile(path.join(root, "ThirdPartyNotices.txt"), path.join(root, directory, "ThirdPartyNotices.txt"));
}
const digest = createHash("sha256").update(bridge).digest("hex");
// The shared core is ported from the website. src/core/provenance.json names the site
// commit and the hash of each site file; every core file must be listed there.
const provenance = JSON.parse(await readFile(path.join(root, "src/core/provenance.json"), "utf8"));
if (!/^[a-f0-9]{40}$/.test(provenance.commit ?? "")) throw new Error("src/core/provenance.json needs the full site commit.");
const coreFiles = (await readdir(path.join(root, "src/core"))).filter(file => file.endsWith(".ts")).map(file => "src/core/" + file);
const unlisted = coreFiles.filter(file => !provenance.files?.[file]);
if (unlisted.length) throw new Error("Core files without provenance: " + unlisted.join(", "));
const core = [];
for (const [file, origin] of Object.entries(provenance.files).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  if (typeof origin.site !== "string" || !/^[a-f0-9]{64}$/.test(origin.siteSHA256 ?? "")) throw new Error("Incomplete provenance: " + file);
  core.push({ file, sha256: createHash("sha256").update(await readFile(path.join(root, file))).digest("hex"), site: origin.site, siteSHA256: origin.siteSHA256, adaptations: origin.adaptations });
}
await writeFile(path.join(root, "docs/protocol-core.json"), JSON.stringify({
  version: packageInfo.version,
  sha256: Object.fromEntries(["dist/cli.mjs", "crates/crabrix/runtime/bridge.mjs", "go/crabrix/runtime/bridge.mjs"].map(file => [file, digest])),
  requires: "Node.js 22+", source: "src/cli.ts and src/core", npmPackage: `crabrix@${packageInfo.version}`,
  documentFormats: [1, 2],
  core: { repository: provenance.repository, commit: provenance.commit, files: core },
}, null, 2) + "\n");
await writeJSON("docs/release-manifest.json", {
  schema: "crabrix-release-manifest-v1", version: packageInfo.version, integrationFamily: "crabrix",
  distribution: { npm: { name: "crabrix", version: packageInfo.version }, claudePlugin: { id: "crabrix@crabrix", version: packageInfo.version }, cargo: { name: "crabrix", version: cargoVersion }, go: { module: "github.com/sergii-ziborov/crabrix-sdk/go/crabrix", version: packageInfo.version } },
  mcp: { serverName: "crabrix", registryName: MCP_NAME, transports: ["stdio"], testedProtocolVersions: TESTED_PROTOCOLS, config: { command: "npx", args: npxArgs } },
  environment: { node: packageInfo.engines.node }, bridgeSHA256: digest,
  publication: "Generated from package.json at build time. It states what this source would release; registry availability needs its own receipt.",
});
