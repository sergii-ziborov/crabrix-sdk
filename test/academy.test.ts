async function startAcademyAPI() {
  const requests: { path: string; ifNoneMatch?: string }[] = [];
  const server = createServer((req, res) => {
    const match = /^\/api\/academy\/v1\/(.+)$/.exec(req.url ?? "");
    requests.push({ path: req.url ?? "", ifNoneMatch: req.headers["if-none-match"] as string | undefined });
    const body = match && match[1] in fixture ? (typeof fixture[match[1]] === "string" ? fixture[match[1]] as string : JSON.stringify(fixture[match[1]])) : null;
    if (!body) { res.writeHead(404, { "Content-Type": "application/json" }); res.end(JSON.stringify({ schemaVersion: 1, error: { code: "NOT_FOUND", message: "No such item." } })); return; }
    const etag = `"${createHash("sha256").update(body).digest("hex").slice(0, 16)}"`;
    if (req.headers["if-none-match"] === etag) { res.writeHead(304, { ETag: etag }); res.end(); return; }
    res.writeHead(200, { "Content-Type": match![1].endsWith(".md") ? "text/markdown; charset=utf-8" : "application/json", ETag: etag });
    res.end(body);
  });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${(server.address() as any).port}`;
  return { origin, requests, close: () => new Promise<void>(resolve => { server.closeAllConnections(); server.close(() => resolve()); }) };
}

async function academyClient(origin: string) {
  const server = makeAcademyServer({ origin }), client = new Client({ name: "academy-test", version: "1" });
  const [a, b] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(a), client.connect(b)]);
  const call = async (name: string, args: Record<string, unknown> = {}) => {
    const result = await client.callTool({ name, arguments: args }) as any;
    return { error: result.isError === true, value: result.structuredContent as any, text: result.content[0].text as string };
  };
  return { client, call, close: () => client.close() };
}

test("ACADEMY-01: the unbound and agent-link tool lists are unchanged unless Academy is asked for", async () => {
  const list = async (server: ReturnType<typeof makeServer>) => {
    const client = new Client({ name: "lists", version: "1" }), [a, b] = InMemoryTransport.createLinkedPair();
    await Promise.all([server.connect(a), client.connect(b)]);
    try { return (await client.listTools()).tools.map(tool => tool.name).sort(); } finally { await client.close(); }
  };
  const room = () => new PlaygroundRoom("http://127.0.0.1:1");
  assert.deepEqual(await list(makeServer(room())), [...UNBOUND].sort());
  assert.deepEqual(await list(makeServer(room(), { bound: true })), [...BOUND].sort());
  // An agent-link session never gains Academy tools, even if asked.
  assert.deepEqual(await list(makeServer(room(), { bound: true, academy: true })), [...BOUND].sort());
  assert.deepEqual(await list(makeServer(room(), { academy: { origin: "http://127.0.0.1:1" } })), [...UNBOUND, ...ACADEMY_TOOLS].sort());
  assert.deepEqual(await list(makeAcademyServer({ origin: "http://127.0.0.1:1" })), [...ACADEMY_TOOLS].sort());
});

